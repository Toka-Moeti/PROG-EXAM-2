    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    try {
    // Note: I am using the variable names from your screenshot. 
    // If your textfields are named differently, change these.
    String customerName = jTextField1.getText();
    String selectedProduct = jComboBox1.getSelectedItem().toString();
    double price = Double.parseDouble(jTextField2.getText());

    if (customerName.isEmpty() || jTextField2.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in all fields.");
        return;
    }

    ProductCalculations calc = new ProductCalculations(price);
    double vat = calc.GetVat();
    double commission = calc.GetCommission();
    double total = calc.GetTotal();

    DecimalFormat df = new DecimalFormat("R #,##0.0");
    String message = "Customer Name: " + customerName + "\n" +
                     "Product: " + selectedProduct + "\n" +
                     "VAT: " + df.format(vat) + "\n" +
                     "COMMISSION: " + df.format(commission) + "\n" +
                     "TOTAL: " + df.format(total);
    
    JOptionPane.showMessageDialog(this, message, "Message", JOptionPane.INFORMATION_MESSAGE);

    try (PrintWriter out = new PrintWriter(new FileWriter("data.txt", true))) {
        out.println("DATA LOG");
        out.println("*******************************");
        out.println("Customer Name: " + customerName);
        out.println("Product: " + selectedProduct);
        out.println("VAT: " + df.format(vat));
        out.println("COMMISSION: " + df.format(commission));
        out.println("TOTAL: " + df.format(total));
        out.println("*******************************\n");
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error saving to file.");
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Please enter a valid numeric price.");
}
    }//GEN-LAST:event_jButton1ActionPerformed

